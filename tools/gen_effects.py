#!/usr/bin/env python3
"""Compile the recordings of the real Air75 V3 (tools/rec-*.txt) into firmware tables: src/core/effect_data.h

Model (all verified against the recordings, see tools/fx_report.py):
  phase_i(t) = P_e[i] + rate_e * speed(gear) * t                  (degrees; i = key LED in the V3's order)
  auto colour   : HSV(phase, S=1, V=200 * brightness%)
  custom colour : colour direction (hue, saturation) of the stored RGB, V = F_e(phase + d_e) * brightness%
"""
import numpy as np, os, sys
from fit import *
from geom import V3_SET

GEAR_RATIO = [5.48 / 175.77, 87.94 / 175.77, 1.0, 263.6 / 175.77, 351.7 / 175.77]     # measured on Ray
BINS = 48
out = []; w = out.append
w("/* GENERATED by tools/gen_effects.py from recordings of a real Air75 V3 - do not edit. */\n#pragma once\n#include <stdint.h>\n")
w("#define FX_BINS %d\n#define FX_LEDS 83\nstatic const float FX_GEAR_RATIO[5] = {%s};\n" % (BINS, ", ".join("%.4ff" % g for g in GEAR_RATIO)))

def h8(deg): return np.round((np.asarray(deg) % 360) / 360 * 256).astype(int) % 256
def arr(name, a, ctype="uint8_t"):
    w("static const %s %s[%d] = {%s};" % (ctype, name, len(a), ", ".join(str(int(x)) for x in a)))

def learn_F(P, rate, e, custom_name):
    tc, rc = load(custom_name); Vc = rc[:, :83].max(-1).astype(float)
    best = None
    for d in np.arange(0, 360, 4):
        phi = (P[None, :] + rate * tc[:, None] + d) % 360
        b = np.clip((phi / 360 * BINS).astype(int), 0, BINS - 1)
        F = np.array([Vc[b == k].mean() if (b == k).any() else np.nan for k in range(BINS)])
        for k in range(BINS):                                 # fill empty bins by neighbours
            if np.isnan(F[k]):
                F[k] = np.nanmean([F[(k - 1) % BINS], F[(k + 1) % BINS]])
        err = np.sqrt(np.nanmean((F[b] - Vc) ** 2))
        if best is None or err < best[0]: best = (err, d, F)
    return best

report = []
w("\n/* hue-field effects: effect id -> rate at gear 2 (deg/s), phase offsets (hue8), custom-colour offset d (hue8) and brightness curve F */")
EFFECTS = {}
for e in (1, 6, 7, 8, 9, 10, 14):
    t, rgb = load(f"back_e{e}_g2_auto")
    r, coh, P = drift_fit(t, rgb)
    P = np.nan_to_num(P)
    F = None
    if e == 9: F = (0, 0, np.full(BINS, 200.0))
    else: F = learn_F(P, r, e, f"back_e{e}_g2_red")
    EFFECTS[e] = (r, P, F)
    report.append(f"e{e}: drift {r:+.1f} deg/s (coh {coh:.3f}); custom-colour curve rms {F[0]:.1f}")
    arr(f"FX_P_{e}", h8(P)); arr(f"FX_F_{e}", np.round(np.clip(F[2], 0, 255)))
    w(f"#define FX_RATE_{e} ({r:.2f}f)\n#define FX_D_{e} {int(h8(F[1]))}")
    if e == 14:                                           # Time: the auto colour is blinked too (V in {0, 200} by hue phase)
        Vauto = rgb[:, :83].max(-1).astype(float)
        b = np.clip((((P[None, :] + r * t[:, None]) % 360) / 360 * BINS).astype(int), 0, BINS - 1)
        FA = np.array([Vauto[b == k].mean() if (b == k).any() else 0.0 for k in range(BINS)])
        arr("FX_FA_14", np.round(np.clip(FA, 0, 255) / 200 * 200))

# Custom-colour brightness of the sweeping effects, fitted per key: V_i(t) = G(t / T + phase_i). A single shared curve over the *hue* phase (above)
# smears Ripple out; fitting each key's own phase recovers the dips (Ripple rms 32 -> 8, Wave 16 -> 6).
def fit_periodic(name, base_deg):
    t, rgb = load(name); V = rgb[:, :83].max(-1).astype(float); t = t - t[0]
    best = None
    for TT in np.arange(360 / abs(base_deg) * 0.95, 360 / abs(base_deg) * 1.05, 0.0015):
        z = (V - V.mean(0)) * np.exp(-2j * np.pi * t[:, None] / TT)
        ph = (np.angle(z.sum(0)) / (2 * np.pi)) % 1
        tau = (t[:, None] / TT + ph[None, :]) % 1; b = np.clip((tau * 40).astype(int), 0, 39)
        mean = np.array([V[b == j].mean() if (b == j).any() else 0 for j in range(40)]); err = np.sqrt(np.mean((mean[b] - V) ** 2))
        if best is None or err < best[0]: best = (err, TT, ph, mean)
    return best
w("\n/* per-key custom-colour model for Ray / Wave / Ripple / Spout: phase_i (1/256 turn), brightness curve over one period, rate in deg/s at gear 2 */")
for e, base in ((1, 176), (6, 176), (7, 176), (8, 346)):
    err, TT, ph, mean = fit_periodic(f"back_e{e}_g2_red", base)
    report.append(f"e{e}: per-key custom-colour fit rms {err:.1f} (period {TT:.3f}s)")
    arr(f"FX_PH_{e}", np.round(ph * 256).astype(int) % 256); arr(f"FX_FC_{e}", np.round(np.clip(mean, 0, 255)))
    w(f"#define FX_PT_{e} ({360.0 / TT:.2f}f)")

# Stair (2): static hue table + custom-colour curve
t, rgb = load("back_e2_g2_auto"); P2 = np.nan_to_num(hue(rgb[len(t)//2, :83]))
F2 = learn_F(P2, 0.0, 2, "back_e2_g2_red"); report.append(f"e2: static; custom-colour curve rms {F2[0]:.1f}")
arr("FX_P_2", h8(P2)); arr("FX_F_2", np.round(np.clip(F2[2], 0, 255))); w(f"#define FX_D_2 {int(h8(F2[1]))}")

# Windmill (19): three blades sweeping round the board. Every key is a sawtooth in time (blade amount jumps to ~0.95 as a blade passes,
# then fades linearly to 0 over one rotation); keys differ only in the phase of the jump. Colour = white + (stored colour - white) * amount.
t, rgb = load("fx_e19_g2_rgbred"); kk = rgb[:, :83].astype(float); t = t - t[0]
amt = (200 - kk[:, :, 1]) / 200.0
jt = [t[np.flatnonzero(np.diff(amt[:, i]) > 0.35) + 1] for i in range(83)]
best = None
for TT in np.arange(1.02, 1.07, 0.001):
    ph = np.array([(np.angle(np.mean(np.exp(2j * np.pi * j / TT))) / (2 * np.pi)) % 1 if len(j) else 0.0 for j in jt])
    tau = (t[:, None] / TT - ph[None, :]) % 1; b = np.clip((tau * 40).astype(int), 0, 39)
    mean = np.array([amt[b == j].mean() for j in range(40)]); err = np.mean((mean[b] - amt) ** 2)
    if best is None or err < best[0]: best = (err, TT, ph, mean)
werr, wT, wph, wmean = best
wmean[-1] = min(wmean[-1], 0.03)                       # the last bin straddles the jump
report.append(f"e19 windmill: period {wT:.3f}s at gear 2, residual {werr:.4f} (variance {amt.var():.4f})")
arr("FX_P_19", np.round(wph * 256).astype(int) % 256); arr("FX_F_19", np.round(np.clip(wmean, 0, 1) * 255))
w(f"#define FX_RATE_19 ({360.0 / wT:.2f}f)")

# Breath (4): uniform hue drift + brightness curve over one period
t, rgb = load("back_e4_g2_auto"); k = rgb[:, :83].astype(float); v = k.max(-1)[:, 10]
x = v - v.mean(); ac = np.correlate(x, x, 'full')[len(x)-1:]; ac /= ac[0]; dt = np.mean(np.diff(t))
pk = [i for i in range(5, len(ac)-1) if ac[i] > ac[i-1] and ac[i] >= ac[i+1] and ac[i] > 0.5]; period = pk[0] * dt
h = hue(rgb[:, 10]); ok = ~np.isnan(h); u = np.degrees(np.unwrap(np.radians(h[ok]))); drift = np.polyfit(t[ok], u, 1)[0]
curve = [v[int(np.searchsorted(t, (j / 64) * period))] for j in range(64)]
report.append(f"e4: breath period {period:.3f}s drift {drift:.2f} deg/s")
arr("FX_BREATH", np.round(curve)); w(f"#define FX_BREATH_PERIOD_MS {int(period*1000)}\n#define FX_BREATH_DRIFT ({drift:.2f}f)")
for g in (0, 4):
    tg, rg = load(f"back_e4_g{g}_auto"); vg = rg[:, :83].max(-1)[:, 10].astype(float); xg = vg - vg.mean(); acg = np.correlate(xg, xg, 'full')[len(xg)-1:]; acg /= acg[0]
    pkg = [i for i in range(5, len(acg)-1) if acg[i] > acg[i-1] and acg[i] >= acg[i+1] and acg[i] > 0.5]
    report.append(f"    breath gear {g}: period {pkg[0]*np.mean(np.diff(tg)):.3f}s" if pkg else f"    breath gear {g}: no period within the window (static or slower than {tg[-1]:.0f}s)")

# Gaming (17) / Identify (18): static highlight sets (V3 LED order), colour comes from the stored RGB (default red)
for e, nm in ((17, "GAMING"), (18, "IDENTIFY")):
    t, rgb = load(f"back_e{e}_g2_auto"); lit = [i for i in range(83) if rgb[10, i].max() > 0]
    w(f"static const uint8_t FX_{nm}_N = {len(lit)};"); arr(f"FX_{nm}_LEDS", lit)

# side lights: 10 LEDs per strip, V=255-class with channel floor
def side(name): t, rgb = load(name); return t, rgb[:, 84:94]
t, s = side("side_e0_g2_auto"); hs = hue(s); u = np.degrees(np.unwrap(np.radians(np.nan_to_num(hs[:, 0])))); sdrift = np.polyfit(t, u, 1)[0]
rel = np.radians(hs) - np.radians(sdrift) * t[:, None]; SP = np.degrees(np.angle(np.nan_to_num(np.exp(1j*rel)).mean(0))) % 360
arr("FX_SIDE_TIME_P", h8(SP)); w(f"#define FX_SIDE_TIME_DRIFT ({sdrift:.2f}f)")
t, s = side("side_e1_g2_auto"); hs = hue(s)[:, 0]; u = np.degrees(np.unwrap(np.radians(np.nan_to_num(hs)))); w(f"#define FX_SIDE_NEON_DRIFT ({np.polyfit(t, u, 1)[0]:.2f}f)")
t, s = side("side_e2_g2_auto"); arr("FX_SIDE_STATIC_RGB", s[len(t)//2].reshape(-1))
t, s = side("side_e3_g2_auto"); vv = s.max(-1)[:, 0]; xs = vv - vv.mean(); acs = np.correlate(xs, xs, 'full')[len(xs)-1:]; acs /= acs[0]
pks = [i for i in range(5, len(acs)-1) if acs[i] > acs[i-1] and acs[i] >= acs[i+1] and acs[i] > 0.3]; sper = (pks[0] if pks else len(t)) * np.mean(np.diff(t))
arr("FX_SIDE_BREATH", np.round([vv[int(np.searchsorted(t, (j / 64) * sper))] for j in range(64)])); w(f"#define FX_SIDE_BREATH_PERIOD_MS {int(sper*1000)}")
report.append(f"side: time drift {sdrift:.1f} deg/s, breathe period {sper:.2f}s")

open("../firmware/air75v2/src/core/effect_data.h", "w").write("\n".join(out) + "\n")
print("\n".join(report)); print("wrote firmware/air75v2/src/core/effect_data.h (%d lines)" % len(out))
